#!/usr/bin/env python
"""E0 audit. Stored-result numbers are computed from the frozen archive results/v1_submitted.
Numbers printed in the submitted PDF are transcribed by hand and labelled as such."""
import csv, glob, os, collections
import numpy as np

V1 = "results/v1_submitted/results"
OUT = "results/v2/audit_report.md"

def load(exp):
    return list(csv.DictReader(open(f"{V1}/{exp}/summary.csv")))

def accd(rows, m, c):
    return {int(r["seed"]): float(r["accuracy"]) * 100 for r in rows if r["method"] == m and r["condition"] == c}

def arr(d, seeds=None):
    return np.array([v for s, v in sorted(d.items()) if seeds is None or s in seeds])

def ms(v):
    return f"{v.mean():.2f}+-{v.std(ddof=1):.2f} (n={len(v)})" if len(v) > 1 else "n/a"

M3 = ["B2_naive", "B5_blind_mask", "B4_rifl_iot"]
big = load("review_seed_scaleup")
L = ["# E0 audit report (generated by scripts/e0_audit.py)", ""]

L += ["## 1. Seeds actually used per experiment and condition", "", "| experiment | seeds per condition |", "|---|---|"]
for d in sorted(glob.glob(f"{V1}/*/summary.csv")):
    exp = d.split("/")[-2]
    rows = list(csv.DictReader(open(d)))
    if not rows or "seed" not in rows[0]:
        continue
    s = collections.defaultdict(set)
    for r in rows:
        s[r["condition"]].add(int(r["seed"]))
    L.append(f"| {exp} | " + ", ".join(f"{c}:{len(x)}" for c, x in sorted(s.items())) + " |")

pairs = [("clean", "phase9_b5_ablation", "clean"), ("noise10", "phase9_b5_ablation", "noise10"),
         ("noise30", "phase9_b5_ablation", "noise30"), ("noise50", "phase9_b5_ablation", "noise50"),
         ("correlated30", "phase9_b5_ablation", "ctrl_corr30"), ("symflip100", "phase9b_symflip100", "ctrl_symflip100")]
L += ["", "## 2. n=5 runs versus the n=50 run (accuracy %)", "",
      "If the n=5 runs are seeds 0-4 of the same code and trajectories, the n=50 subset must match them exactly.", "",
      "| condition | method | n=5 run | n=50 run, seeds 0-4 | n=50 run, all | seeds 0-4 identical |", "|---|---|---|---|---|---|"]
n5mean, n50mean = {}, {}
for c50, exp5, c5 in pairs:
    r5 = load(exp5)
    for m in M3:
        d5, d50 = accd(r5, m, c5), accd(big, m, c50)
        same = len(d5) == 5 and all(s in d50 and abs(d5[s] - d50[s]) < 1e-9 for s in range(5))
        n5mean[(c50, m)], n50mean[(c50, m)] = arr(d5).mean(), arr(d50).mean()
        L.append(f"| {c50} | {m} | {ms(arr(d5))} | {ms(arr(d50, set(range(5))))} | {ms(arr(d50))} | {same} |")

def verdict(paper, n5, n50):
    if all(abs(p - x) < 0.06 for p, x in zip(paper, n5)):
        return "matches the n=5 run"
    if all(abs(p - x) < 0.06 for p, x in zip(paper, n50)):
        return "matches the n=50 run"
    return "matches neither"

items = [("Fig 6b bars and Fig 6a end point (caption says n=50)", "noise50", M3, (67.0, 79.1, 92.5)),
         ("Fig 7a (B2/B5/B4)", "noise50", M3, (67.0, 79.1, 92.5)),
         ("Fig 7c correlated 30 (B2/B5/B4)", "correlated30", M3, (74.4, 82.1, 75.1)),
         ("Fig 7b symmetric (B2/B4)", "symflip100", ["B2_naive", "B4_rifl_iot"], (66.8, 68.3))]
L += ["", "## 3. Figure values (transcribed from the submitted PDF) versus stored results", "",
      "| figure | printed in PDF | n=5 means | n=50 means | verdict |", "|---|---|---|---|---|"]
for name, c, meths, paper in items:
    a = [n5mean[(c, m)] for m in meths]
    b = [n50mean[(c, m)] for m in meths]
    L.append(f"| {name} | {paper} | {[round(x, 2) for x in a]} | {[round(x, 2) for x in b]} | {verdict(paper, a, b)} |")

allm = []
for d in sorted(glob.glob(f"{V1}/*/summary.csv")):
    exp = d.split("/")[-2]
    rows = list(csv.DictReader(open(d)))
    if not rows or "accuracy" not in rows[0]:
        continue
    g = collections.defaultdict(list)
    for r in rows:
        g[(r["method"], r["condition"])].append(float(r["accuracy"]) * 100)
    for (m, c), v in g.items():
        allm.append((exp, m, c, float(np.mean(v)), len(v)))
L += ["", "Nearest stored means to the Fig 7b symmetric values (all experiments, all methods):", ""]
for t in (66.8, 68.3):
    for e, m, c, mean, n in sorted(allm, key=lambda x: abs(x[3] - t))[:3]:
        L.append(f"- target {t}: {e} / {m} / {c} mean={mean:.2f} n={n}")

L += ["", "## 4. Where Table IX drift and delay numbers come from (stored means, accuracy %)", "",
      "Paper: Drift 75.1/74.3/75.1 (B2/B5/B4); Delay 20 93.1/83.7/87.7; Drift+noise 63.1/69.9/74.6; Drift+delay 72.4-74.3.", "",
      "| experiment | condition | stored means by method |", "|---|---|---|"]
for exp, cond in [("phase10_delay", "drift_d0"), ("phase6_clean_drift_b0_b2_b4", "drift"), ("phase6b_checkpoint_tuned", "drift"),
                  ("phase10_delay", "stat_d20"), ("phase12_final_matrix", "drift_noise30"), ("phase12_final_matrix", "drift_delay10")]:
    rows = load(exp)
    meths = sorted(set(r["method"] for r in rows if r["condition"] == cond))
    L.append(f"| {exp} | {cond} | " + "; ".join(f"{m}:{arr(accd(rows, m, cond)).mean():.1f}" for m in meths) + " |")
L += ["", "Per-step logs available for regenerating Fig 8 (methods present under runs/):", ""]
for exp, cond in [("phase10_delay", "drift_d0"), ("phase12_final_matrix", "drift_noise30"), ("phase6_clean_drift_b0_b2_b4", "drift")]:
    meths = sorted(os.path.basename(os.path.dirname(p)) for p in glob.glob(f"runs/{exp}/*/{cond}"))
    L.append(f"- runs/{exp}/*/{cond}: {', '.join(meths)}")

L += ["", "## 5. Convergence-failure seeds, clean condition, n=50 (failure = accuracy < 70%)", "",
      "| method | failed seeds | count |", "|---|---|---|"]
fails = {}
for m in M3:
    d = accd(big, m, "clean")
    fails[m] = sorted(s for s, a in d.items() if a < 70)
    L.append(f"| {m} | {fails[m]} | {len(fails[m])} |")
L.append("")
L.append(f"Failed in all three methods: {sorted(set(fails[M3[0]]) & set(fails[M3[1]]) & set(fails[M3[2]]))}")
L.append(f"Failed in some but not all: {sorted((set(fails[M3[0]]) | set(fails[M3[1]]) | set(fails[M3[2]])) - (set(fails[M3[0]]) & set(fails[M3[1]]) & set(fails[M3[2]])))}")

L += ["", "## 6. Inconsistencies found by reading the submitted PDF (hand-transcribed; section 2-5 numbers are computed above)", "",
      "Figures: no script or notebook in this repo writes any figure (grep for savefig/plt.show found nothing), and no figure file from this project exists under ~/usama. Fig 6, 7, 8 are untraced; they are regenerated from results/v2 in E9.",
      "- Fig 6 caption says n=50; bar labels and curve end points are the n=5 values (see section 3).",
      "- Fig 7a and 7c are n=5 values; Fig 7b symmetric values match no stored run (see section 3); Fig 7 and Fig 5 label the control 'symmetric flip' while the text says replacement.",
      "- Fig 8 shows B5 > B4 > B2 under drift and drift+noise; Table XIII has B4 > B5 > B2 under drift+noise. Its annotations (before ~0.70, trough ~0.35, recovery ~0.60) do not match Table XIV.",
      "Tables and text:",
      "- Table IX is n=50 except the B6 row (n=5, placed in n=50 columns) and the Delay 20 / Drift column (n=5). The B6 text compares 63.7 with B2 67.0 (n=5); at n=50 B2 is 61.85, so B6 is above B2.",
      "- Tables X, XI, XII, XIV are n=5, and Table XIII is n=5 except the conflict column. Table XI caption says 'unless marked' but nothing is marked, and it repeats 92.5/67.0/79.1 beside Table IX's n=50 values for the same condition.",
      "- Introduction: 'clean 93.7 +- 0.4, identical to naive' is an n=5 number; at n=50 B4 is 85.57 and B2 86.78.",
      "- Section VI-C: floor test (75.1) and tuned-constant comparison (74.9 vs 92.5) are n=5 beside n=50 columns.",
      "- Discussion refers to 'Table IX reward columns', which do not exist.",
      "- Section V and Table VII say 2000 steps per run; Table VI and the config say stationary runs are 1000.",
      "- Table V omits B6; 'step-matched tuned B5' is actually tuned-constant B2; reference [59] still contains 'verify final citation'; reference [38] reads 'Schtze'.",
      "- README.md lines 45 and 47 still show n=5 numbers (67.0/79.1/92.5 and 74.4/82.1/75.1)."]
open(OUT, "w").write("\n".join(L) + "\n")
print("\n".join(L))
